#!/usr/bin/env node
/**
 * Copy Firebase / public app URL env vars from the web app into the mobile Expo .env.
 *
 * Usage (from expense-tracker-mobile):
 *   npm run env:copy-from-web
 *   npm run env:copy-from-web -- --source=.env.production
 *   npm run env:copy-from-web -- --web-dir=../expense-tracker --force
 *
 * Maps:
 *   VITE_FIREBASE_*       → EXPO_PUBLIC_FIREBASE_*
 *   VITE_PUBLIC_APP_URL   → EXPO_PUBLIC_APP_URL
 *   VITE_GEMINI_API_KEY   → EXPO_PUBLIC_GEMINI_API_KEY
 *
 * Never copies server-only secrets (TWELVE_DATA, CRON, service accounts, etc.).
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(__dirname, "..");

const KEY_MAP = {
  VITE_FIREBASE_API_KEY: "EXPO_PUBLIC_FIREBASE_API_KEY",
  VITE_FIREBASE_AUTH_DOMAIN: "EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN",
  VITE_FIREBASE_PROJECT_ID: "EXPO_PUBLIC_FIREBASE_PROJECT_ID",
  VITE_FIREBASE_STORAGE_BUCKET: "EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET",
  VITE_FIREBASE_MESSAGING_SENDER: "EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER",
  VITE_FIREBASE_APP_ID: "EXPO_PUBLIC_FIREBASE_APP_ID",
  VITE_PUBLIC_APP_URL: "EXPO_PUBLIC_APP_URL",
  VITE_GEMINI_API_KEY: "EXPO_PUBLIC_GEMINI_API_KEY",
};

const SOURCE_CANDIDATES = [".env", ".env.dev", ".env.staging", ".env.production"];

function parseArgs(argv) {
  const opts = {
    webDir: path.resolve(mobileRoot, "../expense-tracker"),
    source: null,
    out: path.join(mobileRoot, ".env"),
    force: false,
  };

  for (const arg of argv) {
    if (arg === "--force" || arg === "-f") opts.force = true;
    else if (arg.startsWith("--web-dir=")) opts.webDir = path.resolve(mobileRoot, arg.slice(10));
    else if (arg.startsWith("--source=")) opts.source = arg.slice(9);
    else if (arg.startsWith("--out=")) opts.out = path.resolve(mobileRoot, arg.slice(6));
    else if (arg === "--help" || arg === "-h") {
      printHelp();
      process.exit(0);
    }
  }
  return opts;
}

function printHelp() {
  console.log(`Copy web Vite Firebase env → mobile Expo .env

Options:
  --web-dir=<path>   Web project root (default: ../expense-tracker)
  --source=<file>    Env file name inside web dir (default: first of ${SOURCE_CANDIDATES.join(", ")})
  --out=<path>       Output .env path (default: ./.env)
  --force, -f        Overwrite existing mobile .env
  --help, -h         Show help
`);
}

function parseEnvFile(contents) {
  /** @type {Record<string, string>} */
  const map = {};
  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map[key] = value;
  }
  return map;
}

function resolveSourceFile(webDir, sourceOpt) {
  if (sourceOpt) {
    const candidate = path.isAbsolute(sourceOpt)
      ? sourceOpt
      : path.join(webDir, sourceOpt);
    if (!fs.existsSync(candidate)) {
      throw new Error(`Source env file not found: ${candidate}`);
    }
    return candidate;
  }

  for (const name of SOURCE_CANDIDATES) {
    const candidate = path.join(webDir, name);
    if (fs.existsSync(candidate)) return candidate;
  }

  throw new Error(
    `No env file found in ${webDir}. Tried: ${SOURCE_CANDIDATES.join(", ")}`
  );
}

function buildMobileEnv(webVars) {
  const lines = [
    "# Generated by scripts/copy-env-from-web.mjs",
    "# Do not commit this file. Server-only secrets are intentionally omitted.",
    "",
  ];

  /** @type {string[]} */
  const copied = [];
  /** @type {string[]} */
  const missing = [];

  for (const [fromKey, toKey] of Object.entries(KEY_MAP)) {
    const value = webVars[fromKey];
    if (value == null || value === "") {
      missing.push(fromKey);
      lines.push(`${toKey}=`);
      continue;
    }
    copied.push(`${fromKey} → ${toKey}`);
    lines.push(`${toKey}=${value}`);
  }

  lines.push("");
  return { contents: lines.join("\n"), copied, missing };
}

function main() {
  const opts = parseArgs(process.argv.slice(2));

  if (!fs.existsSync(opts.webDir)) {
    console.error(`Web project directory not found: ${opts.webDir}`);
    process.exit(1);
  }

  if (fs.existsSync(opts.out) && !opts.force) {
    console.error(
      `Refusing to overwrite existing ${path.relative(mobileRoot, opts.out) || opts.out}.\n` +
        `Re-run with --force to replace it.`
    );
    process.exit(1);
  }

  const sourceFile = resolveSourceFile(opts.webDir, opts.source);
  const webVars = parseEnvFile(fs.readFileSync(sourceFile, "utf8"));
  const { contents, copied, missing } = buildMobileEnv(webVars);

  fs.writeFileSync(opts.out, contents, "utf8");

  console.log(`Source: ${sourceFile}`);
  console.log(`Wrote:  ${opts.out}`);
  console.log(`Copied ${copied.length} key(s):`);
  for (const item of copied) console.log(`  ✓ ${item}`);
  if (missing.length) {
    console.log(`Missing / empty on web side (${missing.length}):`);
    for (const key of missing) console.log(`  ✗ ${key}`);
  }
  console.log("\nRestart Expo to load env: npx expo start --clear");
}

try {
  main();
} catch (err) {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
}
