import { fullLedgerFixture } from "../../shared/__fixtures__/readModel/fullLedger";
import { getAccountKind } from "../../shared/utils/accountKind";
import { buildCashbackHistory } from "../../shared/utils/cashbackHistory";
import { ledgerRowAccountDeltas, type LedgerRow } from "../../shared/utils/ledgerAccountDeltas";
import { mapDocument, READ_MODEL_TABLES } from "../../shared/utils/readModel/mapping";
import { calculateDashboardSummaries } from "../../shared/utils/reconciliation";

/**
 * SPENDLY-510 — generates supabase-readmodel/tests/golden.sql: the SPENDLY-503
 * golden fixture seeded through the real mapper and readmodel_upsert, then an
 * assertion that every reporting view equals the TypeScript reference for it,
 * to the paisa. scripts/readmodelGolden.test.ts fails if the committed file
 * differs from this output, so the SQL can never drift from the TypeScript.
 *
 *   npx tsx scripts/readmodel-golden.ts   (rewrites the file)
 */

const UID = "golden-user";
const UPDATE_TIME = { seconds: 1_790_000_000, nanoseconds: 0 };
const money = (n: number) => (Math.round(n * 100) / 100).toFixed(2);
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function buildGoldenSql(): string {
  const fx = fullLedgerFixture() as unknown as Record<string, Record<string, unknown>[]>;
  const out: string[] = [
    "-- GENERATED by scripts/readmodel-golden.ts from shared/__fixtures__/readModel/fullLedger.ts.",
    "-- Do not edit: change the fixture or the TypeScript reference and regenerate.",
    "-- SPENDLY-510: every reporting view equals the TypeScript reference, to the paisa.",
    "",
    "begin;",
    "set local role service_role;",
    "",
    "-- Seed: the fixture, mapped exactly as the sync maps it.",
  ];

  for (const spec of READ_MODEL_TABLES) {
    const rows = (fx[spec.collection] ?? []).map((d) =>
      mapDocument(spec, UID, { id: String(d.id), data: d as Record<string, unknown>, updateTime: UPDATE_TIME })
    );
    if (!rows.length) continue;
    out.push(`select public.readmodel_upsert(${lit(spec.table)}, $golden$${JSON.stringify(rows)}$golden$::jsonb);`);
  }

  // ── Expected values from the TypeScript references ──
  const dashboards = calculateDashboardSummaries(fx.expenses as never, fx.incomes as never);
  const periodRows: string[] = [];
  const flowRows: string[] = [];
  for (const [month, s] of [...dashboards].sort()) {
    flowRows.push(`(${lit(month)}, ${money(s.totalExpenses ?? 0)}, ${money(s.totalIncome ?? 0)}, ${s.transactionCount ?? 0})`);
    for (const [key, total] of Object.entries(s.categoryTotals ?? {}).sort()) {
      periodRows.push(`(${lit(month)}, ${lit(key)}, ${money(total)})`);
    }
  }

  const typeName = new Map((fx.accountTypes ?? []).map((t) => [String(t.id), String(t.name ?? "")]));
  const cashbackRows: string[] = [];
  for (const account of fx.accounts ?? []) {
    if (getAccountKind(typeName.get(String(account.typeId)) ?? "") !== "credit") continue;
    const h = buildCashbackHistory(String(account.id), fx.accountPayments as never, fx.expenses as never);
    if (!h.entries.length) continue;
    cashbackRows.push(
      `(${lit(String(account.id))}, ${h.entries.length}, ${money(h.totalReceived)}, ${money(h.totalVoided)}, ${money(h.statementCredits)}, ${money(h.rewards)})`
    );
  }

  // Bank-balance semantics over the Wave 1 rows (borrowings and receivables
  // are not in the read model).
  const ledger: LedgerRow[] = [
    ...(fx.expenses ?? []).map((row) => ({ kind: "expense", row }) as unknown as LedgerRow),
    ...(fx.incomes ?? []).map((row) => ({ kind: "income", row }) as unknown as LedgerRow),
    ...(fx.accountPayments ?? []).map((row) => ({ kind: "accountPayment", row }) as unknown as LedgerRow),
    ...(fx.accountEntries ?? []).map((row) => ({ kind: "accountEntry", row }) as unknown as LedgerRow),
    ...(fx.accountTransfers ?? []).map((row) => ({ kind: "accountTransfer", row }) as unknown as LedgerRow),
  ];
  const net = new Map<string, number>();
  for (const delta of ledger.flatMap(ledgerRowAccountDeltas)) {
    net.set(delta.accountId, (net.get(delta.accountId) ?? 0) + delta.amountDelta);
  }
  const accountRows = [...net].sort().map(([id, n]) => `(${lit(id)}, ${money(n)})`);

  out.push(
    "",
    "-- Expected (TypeScript): calculateDashboardSummaries, buildCashbackHistory, ledgerRowAccountDeltas.",
    `create temp table expected_period_totals (month text, category_key text, total numeric) on commit drop;`,
    `insert into expected_period_totals values\n  ${periodRows.join(",\n  ")};`,
    `create temp table expected_cash_flow (month text, total_expenses numeric, total_income numeric, transaction_count int) on commit drop;`,
    `insert into expected_cash_flow values\n  ${flowRows.join(",\n  ")};`,
    `create temp table expected_cashback (card_id text, entries int, total_received numeric, total_voided numeric, statement_credits numeric, rewards numeric) on commit drop;`,
    `insert into expected_cashback values\n  ${cashbackRows.join(",\n  ")};`,
    `create temp table expected_account_flows (account_id text, net numeric) on commit drop;`,
    `insert into expected_account_flows values\n  ${accountRows.join(",\n  ")};`,
    "",
    "do $$",
    "declare",
    "  diff text;",
    "begin",
    assertSameSet(
      "v_period_totals",
      `select month, category_key, round(total, 2) from public.v_period_totals where uid = '${UID}'`,
      "select month, category_key, round(total, 2) from expected_period_totals"
    ),
    assertSameSet(
      "v_cash_flow_by_month",
      `select month, round(total_expenses, 2), round(total_income, 2), transaction_count from public.v_cash_flow_by_month where uid = '${UID}'`,
      "select month, round(total_expenses, 2), round(total_income, 2), transaction_count from expected_cash_flow"
    ),
    assertSameSet(
      "v_cashback_history",
      `select card_id, entries, round(total_received, 2), round(total_voided, 2), round(statement_credits, 2), round(rewards, 2) from public.v_cashback_history where uid = '${UID}'`,
      "select card_id, entries, round(total_received, 2), round(total_voided, 2), round(statement_credits, 2), round(rewards, 2) from expected_cashback"
    ),
    assertSameSet(
      "v_account_flows",
      `select account_id, round(net, 2) from public.v_account_flows where uid = '${UID}'`,
      "select account_id, round(net, 2) from expected_account_flows"
    ),
    "end",
    "$$;",
    "",
    "rollback;",
    "",
    "select 'read-model golden tests passed (views = TypeScript reference)' as result;",
    ""
  );
  return out.join("\n");
}

function assertSameSet(name: string, actual: string, expected: string): string {
  return [
    `  select string_agg(r::text, '; ') into diff from (`,
    `    (${actual} except ${expected})`,
    `    union all`,
    `    (${expected} except ${actual})`,
    `  ) r;`,
    `  if diff is not null then raise exception '${name} differs from the TypeScript reference: %', diff; end if;`,
  ].join("\n");
}
